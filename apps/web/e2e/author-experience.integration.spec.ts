import { expect, test } from '@playwright/test'
const api='http://127.0.0.1:8796/v1/projects/review-fixture'

test('resume writing → save → history diff → recover selected text → Free review → feedback',async({page,request})=>{
 await page.goto('/?view=read&compose=1&chapter=CH-008')
 const editor=page.getByLabel('正文编辑器')
 await expect(editor).toContainText('林舟到过北港')
 const original=await editor.innerText()
 const yesterday=original+'\n\n昨日删除的一段。'
 await editor.fill(yesterday)
 await expect.poll(async()=> (await(await request.get(api+'/chapters/CH-008')).json()).headRevision.markdown).toContain('昨日删除的一段。')
 const yesterdaySaved=(await(await request.get(api+'/chapters/CH-008')).json()).headRevision.markdown
 await editor.fill(original)
 await expect.poll(async()=> (await(await request.get(api+'/chapters/CH-008')).json()).headRevision.markdown).not.toContain('昨日删除的一段。')
 // Remove explicit URL hints, so reopen must use the account/workspace resume metadata.
 await expect.poll(async()=> (await(await request.get(api+'/workspace')).json()).userState.resume?.compose).toBe(true)
 await page.goto('/')
 await expect(editor).toHaveAttribute('contenteditable','true')
 await expect(editor).toContainText('林舟到过北港')
 await page.getByRole('button',{name:'历史版本',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'历史版本',exact:true})
 const versions=dialog.getByRole('combobox',{name:'选择历史版本'})
 await expect(versions.locator('option')).toHaveCount(3)
 await versions.selectOption({index:1})
 const history=dialog.getByLabel('历史版本正文')
 await expect(history).toHaveValue(yesterdaySaved)
 await expect(dialog.getByText(/^(删除|修改前)$/, { exact: true }).first()).toBeVisible()
 await history.focus()
 // Read-only textareas do not support caret-arrow selection in this headless Chromium.
 // Exercise the same native range + mouse-release path as dragging over a fragment.
 await history.evaluate((area:HTMLTextAreaElement)=>{
  const start=area.value.indexOf('昨日删除的一段。');area.setSelectionRange(start,start+'昨日删除的一段。'.length)
  area.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}))
 })
 await expect(dialog.getByRole('button',{name:'将所选片段追加到章末'})).toBeEnabled()
 await dialog.getByRole('button',{name:'将所选片段追加到章末'}).click()
 await expect(dialog.getByRole('status')).toHaveText('已保存为新版本，之前的版本仍然保留。')
 await dialog.getByRole('button',{name:'关闭',exact:true}).click()
 await expect(editor).toContainText('昨日删除的一段。')
 await page.getByRole('button',{name:'审查与注记',exact:true}).click()
 await expect(page.getByRole('button',{name:'审查',exact:true})).toHaveCount(0)
 await expect(page.getByText(/本月免费审查剩余 2 \/ 2 次/)).toBeVisible()
 await page.getByRole('button',{name:'审查本章',exact:true}).click()
 const consent=page.getByRole('dialog',{name:'确认审查与模型数据发送'})
 await expect(consent).toContainText('最多 217 AI 点数')
 await consent.getByRole('checkbox').last().check()
 await consent.getByRole('button',{name:'确认并发送审查'}).click()
 await page.getByText('两处记录可能存在差异',{exact:true}).click()
 await page.getByRole('button',{name:'有用',exact:true}).click()
 await expect(page.getByText('已标记：有用',{exact:true})).toBeVisible()
 await expect.poll(async()=> (await(await request.get('http://127.0.0.1:8796/v1/account')).json()).review.remaining).toBe(1)
 const saved=(await(await request.get(api+'/chapters/CH-008')).json()).headRevision
 expect(saved.markdown).toContain('昨日删除的一段。')
 await page.screenshot({path:'test-results-author-experience/journey-desktop.png',fullPage:true})
})
test('mobile: history and unified drawer remain accessible in reading mode',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/?view=read&chapter=CH-008')
 await expect(page.getByLabel('正文编辑器')).toHaveAttribute('contenteditable','false')
 await page.getByRole('button',{name:'历史版本',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'历史版本',exact:true})
 await expect(dialog.getByLabel('历史版本正文')).toBeVisible()
 await dialog.getByRole('button',{name:'关闭',exact:true}).click()
 const closeAux=page.getByRole('button',{name:'收起辅助',exact:true})
 if(await closeAux.isVisible())await closeAux.click()
 await page.getByRole('button',{name:'审查与注记',exact:true}).click()
 await expect(page.getByRole('heading',{name:'本章连续性审查'})).toBeVisible()
 await page.getByRole('button',{name:'添加注记',exact:true}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await page.screenshot({path:'test-results-author-experience/journey-mobile.png',fullPage:true})
})
